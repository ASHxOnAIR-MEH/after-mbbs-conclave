/**
 * Normalizes input code to uppercase, trimmed, hyphens standardized
 */
export function normalizeReferralCode(rawCode) {
  if (!rawCode || typeof rawCode !== 'string') return '';
  return rawCode.trim().toUpperCase().replace(/[\s_]+/g, '-');
}

/**
 * Validates referral code against official dataset
 * Returns { valid: true, rep: { name, college, code, year } } or { valid: false, error: string }
 */
export function validateReferralCode(rawCode) {
  const normalized = normalizeReferralCode(rawCode);
  if (!normalized) {
    return {
      valid: false,
      error: 'Please enter a referral code.',
    };
  }

  const cleanInput = normalized.replace(/[^A-Z0-9]/g, '');

  // 1. Exact match on official code
  let found = officialRepresentatives.find(r => r.code === normalized);

  // 2. Exact match on explicit aliases
  if (!found) {
    found = officialRepresentatives.find(r => r.aliases && r.aliases.includes(normalized));
  }

  // 3. Alphanumeric match (e.g. NANGOV016 matches NAN-GOV-016)
  if (!found) {
    found = officialRepresentatives.find(r => {
      const cleanCode = r.code.replace(/[^A-Z0-9]/g, '');
      if (cleanInput === cleanCode) return true;
      if (r.aliases && r.aliases.some(a => a.replace(/[^A-Z0-9]/g, '') === cleanInput)) return true;
      return false;
    });
  }

  // 4. Fallback: if user enters short form with letters & number (e.g. "GOV-016" or "NAN016")
  if (!found && cleanInput.length >= 2) {
    const numMatch = cleanInput.match(/\d+$/);
    if (numMatch) {
      const inputNum = parseInt(numMatch[0], 10);
      found = officialRepresentatives.find(r => {
        const rNum = parseInt(r.code.slice(-3), 10);
        if (rNum === inputNum) {
          const letters = cleanInput.replace(/[0-9]/g, '');
          if (!letters) return false;
          return (
            r.code.replace(/[^A-Z]/g, '').includes(letters) ||
            (r.aliases && r.aliases.some(a => a.replace(/[^A-Z]/g, '').includes(letters)))
          );
        }
        return false;
      });
    }
  }

  if (found) {
    return {
      valid: true,
      rep: {
        id: found.id,
        code: found.code,
        name: found.name,
        college: found.college,
        year: found.year || 'MBBS Student',
      },
    };
  }

  return {
    valid: false,
    error: 'INVALID REFERRAL CODE. Please enter a valid official referral code provided by an IMA Parippally Student Team representative.',
  };
}
